export function makeT(lang) {
  const dict = STRINGS[lang === 'en' ? 'en' : 'pt'];
  return (key) => dict[key] ?? STRINGS.pt[key] ?? key;
}

export function linePair(obj, lang) {
  if (!obj) return { primary: '', secondary: '' };
  if (typeof obj === 'string') return { primary: obj, secondary: '' };
  const pt = obj.pt || obj.en || '';
  const en = obj.en || obj.pt || '';
  return lang === 'en' ? { primary: en, secondary: pt } : { primary: pt, secondary: en };
}
